import opentype from 'opentype.js'
import { GLYPHS, LETTERS, isEmpty, type Format, type Glyphs } from './font'

export class ValidationError extends Error {
  problems: string[]
  constructor(problems: string[]) {
    super(problems.join('\n'))
    this.problems = problems
  }
}

/** Font family names go into the `name` table: keep them printable ASCII. */
export function sanitizeName(raw: string): string {
  return raw.replace(/[^\x20-\x7e]/g, '').replace(/\s+/g, ' ').trim().slice(0, 63)
}

/** 1. Checks on user input, before building anything. */
export function validateInput(glyphs: Glyphs, rawName: string): string[] {
  const problems: string[] = []
  if (!sanitizeName(rawName)) problems.push('Enter a font name (letters, numbers, spaces; no special characters only).')
  if (!GLYPHS.some((c) => glyphs[c] && !isEmpty(glyphs[c]))) {
    problems.push('No glyphs drawn yet. Draw at least one character before exporting.')
  }
  return problems
}

const EXPECTED_MAGIC: Record<Format, string> = { otf: 'OTTO', ttf: '\0\x01\0\0', woff: 'wOFF' }
const REQUIRED_TABLES = ['cmap', 'head', 'hhea', 'hmtx', 'maxp', 'name', 'OS/2', 'post']

const tag = (v: DataView, off: number) =>
  String.fromCharCode(v.getUint8(off), v.getUint8(off + 1), v.getUint8(off + 2), v.getUint8(off + 3))

function tableTags(v: DataView, isWoff: boolean): string[] {
  const n = v.getUint16(isWoff ? 12 : 4)
  const start = isWoff ? 44 : 12
  const size = isWoff ? 20 : 16
  return Array.from({ length: n }, (_, i) => tag(v, start + i * size))
}

/** 2. Re-parse the generated bytes and check structure + contents. */
export function validateOutput(buf: ArrayBuffer, format: Format, glyphs: Glyphs): string[] {
  const problems: string[] = []
  if (buf.byteLength < 12) return ['Generated file is empty or truncated.']
  const view = new DataView(buf)
  const magic = tag(view, 0)
  if (magic !== EXPECTED_MAGIC[format]) {
    problems.push(`Wrong file header for .${format} (got "${magic.replace(/\0/g, '\\0')}").`)
    return problems
  }

  // Table directory (for woff, the flavor says which outline type is inside)
  const tags = tableTags(view, format === 'woff')
  const flavor = format === 'woff' ? tag(view, 4) : magic
  const outlines = flavor === 'OTTO' ? ['CFF '] : ['glyf', 'loca']
  for (const t of [...REQUIRED_TABLES, ...outlines]) {
    if (!tags.includes(t)) problems.push(`Missing required table "${t}".`)
  }
  if (format === 'ttf' && flavor === 'OTTO') problems.push('.ttf contains CFF outlines; expected TrueType outlines.')
  if (format === 'otf' && flavor !== 'OTTO') problems.push('.otf contains TrueType outlines; expected CFF outlines.')
  if (problems.length) return problems

  let font: opentype.Font
  try {
    font = opentype.parse(buf)
  } catch (e) {
    return [`Generated font could not be parsed: ${e instanceof Error ? e.message : e}`]
  }

  if (font.unitsPerEm < 16 || font.unitsPerEm > 16384) problems.push(`Invalid unitsPerEm (${font.unitsPerEm}).`)
  // TrueType fonts may use post v3 (no glyph names); only check names when present.
  const first = font.glyphs.get(0)
  if (!first) problems.push('Font has no glyphs.')
  else if (first.name && first.name !== '.notdef') problems.push('First glyph must be .notdef.')

  const names = new Set<string>()
  for (let i = 0; i < font.glyphs.length; i++) {
    const n = font.glyphs.get(i).name
    if (n && names.has(n)) problems.push(`Duplicate glyph name "${n}".`)
    if (n) names.add(n)
  }

  const check = (ch: string, source: string) => {
    const g = font.charToGlyph(ch)
    if (!g || g.index === 0) { problems.push(`"${ch}" is not mapped in the font's cmap.`); return }
    const drawn = !isEmpty(glyphs[source])
    const hasOutline = g.getPath(0, 0, font.unitsPerEm).commands.length > 0
    if (drawn && !hasOutline) problems.push(`"${ch}" was drawn but has no outline in the exported font.`)
    if (!drawn && hasOutline) problems.push(`"${ch}" is blank but has an outline in the exported font.`)
  }
  for (const ch of GLYPHS) check(ch, ch)
  for (const l of LETTERS) check(l.toLowerCase(), l)

  return problems
}

/** 3. Ask the browser (OTS sanitizer) to actually load the font. */
export async function validateInBrowser(buf: ArrayBuffer, family: string): Promise<string[]> {
  if (typeof FontFace === 'undefined') return []
  try {
    const face = new FontFace(family, buf.slice(0))
    await face.load()
    return []
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e)
    return [`The browser rejected the font file: ${msg}`]
  }
}

/** Run all checks; throws ValidationError listing every problem found. */
export async function validateExport(glyphs: Glyphs, rawName: string, format: Format, build: (name: string) => ArrayBuffer) {
  const inputProblems = validateInput(glyphs, rawName)
  if (inputProblems.length) throw new ValidationError(inputProblems)
  const name = sanitizeName(rawName)
  const buf = build(name)
  const problems = [
    ...validateOutput(buf, format, glyphs),
    ...(await validateInBrowser(buf, name)),
  ]
  if (problems.length) throw new ValidationError(problems)
  return { buf, name }
}
